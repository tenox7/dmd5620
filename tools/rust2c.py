#!/usr/bin/env python3
"""Generate core/rom.c and core/optable.h from the Rust dmd_core sources.

Run once, from the repo root, with a dmd_core checkout:
    python3 tools/rust2c.py /path/to/dmd_core/src

rom.c holds the four firmware ROM images (V1 = 8;7;3, V2 = 8;7;5).
optable.h holds the WE32100 mnemonic tables (the decoder's view).
"""
import hashlib
import re
import sys

src = sys.argv[1]


def rom_arrays(path):
    text = open(path).read()
    out = {}
    for m in re.finditer(r"pub static (\w+): \[u8; (\w+)\] = \[(.*?)\];", text, re.S):
        name, data = m.group(1), m.group(3)
        out[name] = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", data))
    return out


roms = {}
roms.update(rom_arrays(src + "/rom_lo.rs"))
roms.update(rom_arrays(src + "/rom_hi.rs"))
assert len(roms["LO_ROM_V1"]) == 0x8000 and len(roms["HI_ROM_V1"]) == 0x8000
assert len(roms["LO_ROM_V2"]) == 0x10000 and len(roms["HI_ROM_V2"]) == 0x10000

with open("core/rom.c", "w") as f:
    f.write("/* Firmware ROM images of the AT&T / Teletype DMD 5620.\n")
    f.write(" * Generated by tools/rust2c.py from dmd_core 0.7.2 (rom_lo.rs, rom_hi.rs).\n")
    f.write(" * Do not edit. V1 = firmware 8;7;3, V2 = firmware 8;7;5.\n")
    for name in ("LO_ROM_V1", "HI_ROM_V1", "LO_ROM_V2", "HI_ROM_V2"):
        f.write(" *   %-9s sha256 %s\n" % (name, hashlib.sha256(roms[name]).hexdigest()))
    f.write(" */\n\n#include \"core.h\"\n")
    for name in ("LO_ROM_V1", "HI_ROM_V1", "LO_ROM_V2", "HI_ROM_V2"):
        data = roms[name]
        f.write("\nconst uint8_t %s[%#x] = {\n" % (name.lower(), len(data)))
        for i in range(0, len(data), 16):
            f.write("    " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
        f.write("};\n")

# Mnemonic tables from cpu.rs
cpu = open(src + "/cpu.rs").read()
DT = {"None": "D_NONE", "Byte": "D_BYTE", "Half": "D_HALF", "Word": "D_WORD"}
OT = {"None": "OT_NONE", "Lit": "OT_LIT", "Src": "OT_SRC", "Dest": "OT_DEST"}
mn_re = re.compile(
    r'Some\(mn!\(\s*(0x[0-9a-fA-F]+),\s*Data::(\w+),\s*"(\w+)",\s*'
    r'\[OpType::(\w+),\s*OpType::(\w+),\s*OpType::(\w+),\s*OpType::(\w+)\]\s*\)\)|(None)')


def table(start_marker):
    i = cpu.index(start_marker)
    body = cpu[cpu.index("[", cpu.index("=", i)) + 1:]
    body = body[:body.index("\n];")]
    rows = []
    for m in mn_re.finditer(body):
        if m.group(8):
            rows.append(None)
        else:
            rows.append((int(m.group(1), 16), DT[m.group(2)], m.group(3),
                         [OT[m.group(k)] for k in range(4, 8)]))
    return rows


byte_tab = table("static BYTE_MNEMONICS")
half_tab = table("static HALFWORD_MNEMONICS")
assert len(byte_tab) == 256, len(byte_tab)
assert len(half_tab) == 11, len(half_tab)
for i, row in enumerate(byte_tab):
    assert row is None or row[0] == i, (i, row)

with open("core/optable.h", "w") as f:
    f.write("/* WE32100 mnemonic tables. Generated by tools/rust2c.py from\n")
    f.write(" * dmd_core 0.7.2 cpu.rs. Do not edit. */\n\n")
    f.write("static const struct mnemonic byte_mnemonics[256] = {\n")
    for i, row in enumerate(byte_tab):
        if row is None:
            f.write("    { 0, 0, D_NONE, NULL, { OT_NONE, OT_NONE, OT_NONE, OT_NONE } }, /* %02X */\n" % i)
        else:
            f.write('    { 1, 0x%02X, %s, "%s", { %s } },\n' % (row[0], row[1], row[2], ", ".join(row[3])))
    f.write("};\n\n")
    f.write("static const struct mnemonic halfword_mnemonics[%d] = {\n" % len(half_tab))
    for row in half_tab:
        f.write('    { 1, 0x%04X, %s, "%s", { %s } },\n' % (row[0], row[1], row[2], ", ".join(row[3])))
    f.write("};\n")

print("wrote core/rom.c and core/optable.h")
